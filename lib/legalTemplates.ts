import type { SiteSettingsData } from './siteSettings';

const PLACEHOLDERS = {
  ENTITY: '[ИП "Имя Фамилия"]',
  REQUISITES: '[ИИН/БИН]',
  ADDRESS: '[юридический адрес]',
  EMAIL: '[email поддержки]',
  PHONE: '[телефон]',
  BRAND: 'KursGalaxy.kz',
};

function fill(s: SiteSettingsData, brandName: string): typeof PLACEHOLDERS {
  return {
    ENTITY: s.legalEntityName || PLACEHOLDERS.ENTITY,
    REQUISITES: s.legalRequisites || PLACEHOLDERS.REQUISITES,
    ADDRESS: s.legalAddress || PLACEHOLDERS.ADDRESS,
    EMAIL: s.contactEmail || PLACEHOLDERS.EMAIL,
    PHONE: s.contactPhone || PLACEHOLDERS.PHONE,
    BRAND: brandName,
  };
}

